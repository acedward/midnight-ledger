#[test]
fn every_generated_anchor_record_replays_byte_exactly() {
    let mut checked = 0usize;
    for r in parse("anchor.txt") {
        let Some(nullifier_hex) = r.maybe("nullifier") else {
            continue; // the constants record
        };
        let nullifier = nullifier_from(nullifier_hex);
        let binding = BindingElement::new(r.field("h")).expect("frozen h is nonzero");
        let anchor = AnchorV1::new(nullifier, binding);

        // The six field elements, in order.
        let ciph = anchor.encode();
        let carried = r.all("field");
        assert_eq!(carried.len(), 6, "{}", r.name);
        for (i, theirs) in carried.iter().enumerate() {
            assert_eq!(
                hexed(&fr_le32(ciph.ciph[i])),
                *theirs,
                "{} ciph[{i}]",
                r.name
            );
        }

        // The untagged wire form: bytes, length and digest.
        let untagged = anchor.encode_untagged_bytes();
        assert_eq!(hexed(&untagged), r.one("untagged"), "{} untagged", r.name);
        assert_eq!(untagged.len(), r.num("untagged_len") as usize, "{}", r.name);
        assert_eq!(
            sha256_hex(&untagged),
            r.one("untagged_sha256"),
            "{}",
            r.name
        );

        // The tagged, standalone-artifact form.
        let mut tagged = Vec::new();
        tagged_serialize(&ciph, &mut tagged).unwrap();
        assert_eq!(tagged.len(), r.num("tagged_len") as usize, "{}", r.name);
        assert_eq!(sha256_hex(&tagged), r.one("tagged_sha256"), "{}", r.name);

        // ...and decoding gets the same pair back.
        let decoded = AnchorV1::decode_untagged_bytes(&untagged).expect("frozen anchors decode");
        assert_eq!(decoded.nullifier, nullifier, "{}", r.name);
        assert_eq!(decoded.binding, binding, "{}", r.name);
        checked += 1;
    }
    assert_eq!(checked, 5);
}

/// The untagged encoding has no fixed width, and the frozen records prove it
