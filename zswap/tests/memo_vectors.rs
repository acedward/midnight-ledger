#[test]
fn every_generated_anchor_record_replays_byte_exactly() {
    let mut checked = 0usize;
    for r in parse("anchor.txt") {
        let Some(nullifier_hex) = r.maybe("nullifier") else {
            continue; // the constants record
        };
        let nullifier = nullifier_from(nullifier_hex);
        let binding = BindingElement::new(r.field("h")).expect("frozen h is nonzero");
        let anchor = AnchorV1::new(nullifier, binding);

        // The six field elements, in order.
        let ciph = anchor.encode();
        let carried = r.all("field");
        assert_eq!(carried.len(), 6, "{}", r.name);
        for (i, theirs) in carried.iter().enumerate() {
            assert_eq!(
                hexed(&fr_le32(ciph.ciph[i])),
                *theirs,
                "{} ciph[{i}]",
                r.name
            );
        }

        // The untagged wire form: bytes, length and digest.
        let untagged = anchor.encode_untagged_bytes();
        assert_eq!(hexed(&untagged), r.one("untagged"), "{} untagged", r.name);
        assert_eq!(untagged.len(), r.num("untagged_len") as usize, "{}", r.name);
        assert_eq!(
            sha256_hex(&untagged),
            r.one("untagged_sha256"),
            "{}",
            r.name
        );

        // The tagged, standalone-artifact form.
        let mut tagged = Vec::new();
        tagged_serialize(&ciph, &mut tagged).unwrap();
        assert_eq!(tagged.len(), r.num("tagged_len") as usize, "{}", r.name);
        assert_eq!(sha256_hex(&tagged), r.one("tagged_sha256"), "{}", r.name);

        // ...and decoding gets the same pair back.
        let decoded = AnchorV1::decode_untagged_bytes(&untagged).expect("frozen anchors decode");
        assert_eq!(decoded.nullifier, nullifier, "{}", r.name);
        assert_eq!(decoded.binding, binding, "{}", r.name);
        checked += 1;
    }
    assert_eq!(checked, 5);
}

/// The untagged encoding has no fixed width, and the frozen records prove it
/// rather than merely asserting it — a scanner that assumed one would be wrong.
#[test]
fn the_frozen_anchor_lengths_are_not_all_equal() {
    let lengths: Vec<u64> = parse("anchor.txt")
        .iter()
        .filter_map(|r| r.maybe("untagged_len").map(|v| v.parse().unwrap()))
        .collect();
    assert!(lengths.len() >= 4);
    assert!(
        lengths.iter().any(|l| *l != lengths[0]),
        "every frozen anchor had the same length: {lengths:?}"
    );
}

/// The anchor an **unmodified node** validated, applied and finalized.
///
/// Reproducing these exact bytes means these helpers emit a ciphertext a live
/// network has already settled — not merely one this crate agrees with itself
/// about.
#[test]
fn the_settled_anchor_is_reproduced_byte_exactly() {
    let r = &parse("inherited/00003-phase0-anchor.txt")[0];
    let nullifier = nullifier_from(r.one("nullifier"));
    let binding = BindingElement::new(r.field("h")).unwrap();
    let anchor = AnchorV1::new(nullifier, binding);

    let untagged = anchor.encode_untagged_bytes();
    assert_eq!(hexed(&untagged), r.one("untagged"));
    assert_eq!(untagged.len(), r.num("untagged_len") as usize);
    assert_eq!(sha256_hex(&untagged), r.one("untagged_sha256"));

    let mut tagged = Vec::new();
    tagged_serialize(&anchor.encode(), &mut tagged).unwrap();
    assert_eq!(hexed(&tagged), r.one("tagged"));
    assert_eq!(tagged.len(), r.num("tagged_len") as usize);
    assert_eq!(sha256_hex(&tagged), r.one("tagged_sha256"));

    // `h` there is an explicit test constant, not a MemoHashV1 output.
    assert_eq!(
        Fr::from_le_bytes(r.one("h_ascii").as_bytes()).unwrap(),
        binding.get()
    );

    let decoded = AnchorV1::decode_untagged_bytes(&untagged).unwrap();
    assert_eq!(decoded, anchor);
}

