/// Decode the frozen container bytes, check every parsed field against the
/// record, and re-encode: the result must be the same byte string.
///
/// The re-encode half is the one that matters. It is what proves this codec is
/// canonical *and* agrees with the other implementation about section order,
/// framing and exact consumption — a decoder that were merely permissive would
/// pass the field checks and fail here.
#[test]
fn every_frozen_wrapper_record_replays_byte_exactly() {
    let mut checked = 0usize;
    for r in parse("wrapper.txt") {
        let Some(encoded_hex) = r.maybe("encoded") else {
            continue; // the constants record
        };
        let encoded = unhex(encoded_hex);
        assert_eq!(encoded.len(), r.num("encoded_len") as usize, "{}", r.name);
        assert_eq!(sha256_hex(&encoded), r.one("encoded_sha256"), "{}", r.name);

        let w = MemoWrapperV1::decode(&encoded)
            .unwrap_or_else(|e| panic!("{} did not decode: {e}", r.name));

        assert_eq!(
            hexed(w.unverified_memo().as_bytes()),
            r.one("memo"),
            "{} memo",
            r.name
        );
        assert_eq!(
            w.unverified_memo().len(),
            r.num("memo_len") as usize,
            "{} memo_len",
            r.name
        );
        assert_eq!(hexed(&w.nullifier().0.0), r.one("nullifier"), "{}", r.name);
        assert_eq!(w.segment() as u64, r.num("segment"), "{}", r.name);

        assert_eq!(
            w.claimed_statement_tail().len(),
            r.num("statement_rows") as usize,
            "{}",
            r.name
        );
        let mut tail = Vec::new();
        for row in w.claimed_statement_tail() {
            tail.extend_from_slice(&fr_le32(*row));
        }
        assert_eq!(sha256_hex(&tail), r.one("statement_sha256"), "{}", r.name);

        assert_eq!(
            w.companion_proof_bytes().len(),
            r.num("proof_len") as usize,
            "{}",
            r.name
        );
        assert_eq!(
            sha256_hex(w.companion_proof_bytes()),
            r.one("proof_sha256"),
            "{}",
            r.name
        );

        match r.one("locator") {
            "-" => {
                assert!(w.locator().is_none(), "{} carried a locator", r.name);
                assert_eq!(r.num("locator_len"), 0);
            }
            hex => {
                let locator = w.locator().expect("record declares a locator");
                assert_eq!(hexed(locator.as_untrusted_bytes()), hex, "{}", r.name);
                assert_eq!(
                    locator.as_untrusted_bytes().len(),
                    r.num("locator_len") as usize
                );
            }
        }

        // The half that makes this a conformance check rather than a
        // permissiveness check.
        assert_eq!(
            w.encode(),
            encoded,
            "{} did not re-encode identically",
            r.name
        );
        assert_eq!(w.encoded_len(), encoded.len(), "{}", r.name);
        checked += 1;
    }
    assert_eq!(checked, 5);
}

#[test]
fn the_frozen_wrappers_cover_the_boundaries_that_matter() {
    let records = parse("wrapper.txt");
    let memo_lengths: Vec<u64> = records
        .iter()
        .filter_map(|r| r.maybe("memo_len").map(|v| v.parse().unwrap()))
        .collect();
    for boundary in [1u64, 31, 32, 512] {
        assert!(
            memo_lengths.contains(&boundary),
            "no wrapper for {boundary} bytes"
        );
    }
    assert!(
        records.iter().any(|r| r.maybe("locator") == Some("-")),
        "no wrapper without a locator"
    );
    assert!(
        records
            .iter()
            .any(|r| r.maybe("locator").is_some_and(|l| l != "-")),
        "no wrapper with a locator"
    );
    let segments: Vec<u64> = records
        .iter()
        .filter_map(|r| r.maybe("segment").map(|v| v.parse().unwrap()))
        .collect();
    assert!(segments.contains(&0));
    assert!(segments.contains(&(u16::MAX as u64)));
}

// ---------------------------------------------------------------------------
// Anchor decoding through a real `CoinCiphertext` round trip, so the frozen
// bytes are exercised the way a scanner over a transaction would meet them.
// ---------------------------------------------------------------------------

#[test]
fn frozen_anchors_are_found_by_a_scan_over_surrounding_noise() {
    for r in parse("anchor.txt") {
        let Some(nullifier_hex) = r.maybe("nullifier") else {
            continue;
        };
        let untagged = unhex(r.one("untagged"));
        let mut haystack = vec![0x5au8; 23];
        haystack.extend_from_slice(&untagged);
        haystack.extend_from_slice(&[0xffu8; 17]);

        let found = midnight_zswap::memo::anchor::scan_untagged_anchors(&haystack);
        assert_eq!(found.len(), 1, "{}", r.name);
        assert_eq!(found[0].offset, 23);
        assert_eq!(found[0].len, untagged.len());
        assert_eq!(found[0].anchor.nullifier, nullifier_from(nullifier_hex));

        // ...and the ciphertext really does deserialize as a CoinCiphertext.
        let mut cursor = &untagged[..];
        let ciph = <CoinCiphertext as serialize::Deserializable>::deserialize(&mut cursor, 0)
            .expect("frozen anchors are readable ciphertexts");
        assert!(cursor.is_empty());
        assert!(midnight_zswap::memo::anchor::is_anchor_shaped(&ciph));
    }
}
