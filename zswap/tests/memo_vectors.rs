#[test]
fn every_generated_memo_hash_record_replays_byte_exactly() {
    let mut checked = 0usize;
    for r in parse("memo-hash.txt") {
        if r.maybe("absent") == Some("true") {
            // Absence is the reserved zero and is refused as a binding element.
            assert_eq!(r.hex("memo_hash"), [0u8; 32]);
            assert!(BindingElement::new(Fr::from(0u64)).is_err());
            continue;
        }
        let Some(memo_hex) = r.maybe("memo") else {
            continue; // the constants record
        };
        let bytes = unhex(memo_hex);
        assert_eq!(bytes.len(), r.num("memo_len") as usize, "{}", r.name);

        let packed = pack_memo_bytes(&bytes);
        let carried = r.all("field");
        assert_eq!(packed.len(), r.num("field_count") as usize, "{}", r.name);
        assert_eq!(packed.len(), carried.len(), "{}", r.name);
        for (i, (mine, theirs)) in packed.iter().zip(carried.iter()).enumerate() {
            assert_eq!(hexed(&fr_le32(*mine)), *theirs, "{} field {i}", r.name);
        }

        let memo = Memo::from_slice(&bytes).expect("frozen memos are in range");
        assert_eq!(
            hexed(&fr_le32(memo_hash_v1(&memo))),
            r.one("memo_hash"),
            "{} memo_hash",
            r.name
        );
        checked += 1;
    }
    assert!(checked >= 16, "only {checked} memo-hash records replayed");
}

/// The strongest cross-implementation evidence available: a table published by
/// a *third* implementation, reproduced byte for byte.
#[test]
fn the_inherited_memo_hash_table_replays_byte_exactly() {
    let mut checked = 0usize;
    for r in parse("inherited/00001-memo-hash.txt") {
        if r.maybe("absent") == Some("true") {
            assert_eq!(r.hex("memo_hash"), [0u8; 32]);
            continue;
        }
        let bytes = r.hex("memo");
        assert_eq!(bytes.len(), r.num("memo_len") as usize, "{}", r.name);
        let memo = Memo::from_slice(&bytes).unwrap();
        assert_eq!(
            hexed(&fr_le32(memo_hash_v1(&memo))),
            r.one("memo_hash"),
            "{}",
            r.name
        );
        checked += 1;
    }
    assert_eq!(checked, 5, "the inherited table has five present-memo rows");
}

