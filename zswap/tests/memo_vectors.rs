// ---------------------------------------------------------------------------
// A deliberately strict little parser. It refuses anything it does not
// understand rather than skipping it, so a malformed vector file fails loudly
// instead of silently testing nothing.
// ---------------------------------------------------------------------------

#[derive(Debug, Default)]
struct Record {
    name: String,
    keys: BTreeMap<String, Vec<String>>,
}

impl Record {
    fn one(&self, key: &str) -> &str {
        let values = self
            .keys
            .get(key)
            .unwrap_or_else(|| panic!("record {} has no {key}", self.name));
        assert_eq!(
            values.len(),
            1,
            "record {} has {} values for {key}, expected 1",
            self.name,
            values.len()
        );
        &values[0]
    }

    fn maybe(&self, key: &str) -> Option<&str> {
        self.keys.get(key).map(|v| {
            assert_eq!(v.len(), 1);
            v[0].as_str()
        })
    }

    fn all(&self, key: &str) -> &[String] {
        self.keys.get(key).map(|v| &v[..]).unwrap_or(&[])
    }

    fn hex(&self, key: &str) -> Vec<u8> {
        unhex(self.one(key))
    }

    fn num(&self, key: &str) -> u64 {
        self.one(key)
            .parse()
            .unwrap_or_else(|_| panic!("record {} key {key} is not a number", self.name))
    }

    fn field(&self, key: &str) -> Fr {
        let bytes = self.hex(key);
        assert_eq!(
            bytes.len(),
            32,
            "record {} key {key} is not 32 bytes",
            self.name
        );
        Fr::from_le_bytes(&bytes)
            .unwrap_or_else(|| panic!("record {} key {key} is not a canonical Fr", self.name))
    }
}

fn unhex(s: &str) -> Vec<u8> {
    assert!(s.len().is_multiple_of(2), "odd-length hex: {s}");
    assert!(
        s.bytes()
            .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()),
        "hex must be lowercase with no separators: {s}"
    );
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn hexed(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// SHA-256, via `base_crypto`'s own `persistent_hash`, so this test file adds
/// no dependency to the crate.
fn sha256_hex(bytes: &[u8]) -> String {
    hexed(&persistent_hash(bytes).0)
}

fn vectors_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("memo-vectors")
}

fn parse(file: &str) -> Vec<Record> {
    let path = vectors_dir().join(file);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let mut out: Vec<Record> = Vec::new();
    for (lineno, raw) in text.lines().enumerate() {
        let line = raw.trim_end();
        if line.trim().is_empty() || line.trim_start().starts_with('#') {
            continue;
        }
        let (key, value) = line
            .split_once(": ")
            .or_else(|| line.strip_suffix(':').map(|k| (k, "")))
            .unwrap_or_else(|| {
                panic!("{}:{}: not a `key: value` line: {line:?}", file, lineno + 1)
            });
        if key == "vector" {
            out.push(Record {
                name: value.to_string(),
                keys: BTreeMap::new(),
            });
        } else {
            let record = out.last_mut().unwrap_or_else(|| {
                panic!("{}:{}: `{key}` before any `vector:` line", file, lineno + 1)
            });
            record
                .keys
                .entry(key.to_string())
                .or_default()
                .push(value.to_string());
        }
    }
    assert!(!out.is_empty(), "{file} contained no records");
    out
}

fn nullifier_from(hex: &str) -> Nullifier {
    let bytes = unhex(hex);
    assert_eq!(bytes.len(), 32);
    let mut raw = [0u8; 32];
    raw.copy_from_slice(&bytes);
    Nullifier(HashOutput(raw))
}

