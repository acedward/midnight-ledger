#[test]
fn the_parser_reads_records_keys_and_repeats_in_order() {
    let records = parse("memo-hash.txt");
    assert_eq!(records[0].name, "memo-hash/derivation-constants");
    let hello = records
        .iter()
        .find(|r| r.name == "memo-hash/ascii-hello-world")
        .expect("the hello-world record is present");
    assert_eq!(hello.one("memo_len"), "11");
    assert_eq!(hello.all("field").len(), 2);
    // Repeats keep file order: element 0 is the length prefix.
    assert_eq!(&hello.all("field")[0][..4], "0b00");
}

#[test]
