//! Byte-exact replay of the frozen conformance vectors in `tests/memo-vectors/`.
//!
//! Every value here was produced by a **different** implementation of the same
//! protocol (see `tests/memo-vectors/README.md`). A failure in this file means
//! these helpers diverged from it — which is the one thing cross-implementation
//! equality exists to catch, and the reason none of these files is generated by
//! this crate.

